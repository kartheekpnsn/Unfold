#!/usr/bin/env node
// sync-agents.mjs: one source, three harnesses.
//   .claude/skills         -> symlink to .agents/skills (Claude Code reads skills from there)
//   agents/<name>.md       -> .claude/agents/<name>.md, .codex/agents/<name>.toml, .github/agents/<name>.agent.md
// Run after editing a skill or an agent. `--check` exits 1 if anything generated is stale.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, symlinkSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const stale = [];
const HEADER = 'Generated by scripts/sync-agents.mjs from agents/{name}.md. Do not edit; edit the source and re-run `node scripts/sync-agents.mjs`.';

function write(path, content) {
  const full = join(root, path);
  const cur = existsSync(full) ? readFileSync(full, 'utf8') : null;
  if (cur === content) return;
  if (check) { stale.push(path); return; }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content);
  console.log('wrote ' + path);
}

// ---------- skills: .claude/skills is a symlink to .agents/skills (one copy, both tools read it) ----------
const link = join(root, '.claude', 'skills');
if (!existsSync(link)) {
  if (check) stale.push('.claude/skills (symlink missing)');
  else { mkdirSync(join(root, '.claude'), { recursive: true }); symlinkSync('../.agents/skills', link); console.log('linked .claude/skills -> .agents/skills'); }
}

// ---------- agents ----------
function parseAgent(file) {
  const raw = readFileSync(file, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: missing frontmatter`);
  const meta = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i < 0) continue;
    const k = line.slice(0, i).trim(), v = line.slice(i + 1).trim();
    meta[k] = v.startsWith('[') ? v.slice(1, -1).split(',').map(s => s.trim()).filter(Boolean) : v;
  }
  for (const k of ['name', 'description']) if (!meta[k]) throw new Error(`${file}: frontmatter needs ${k}`);
  // no `tools` = the agent inherits every tool (the main unfold agent needs to ask questions and start subagents)
  return { ...meta, body: m[2].trim() + '\n' };
}
// abstract tool names -> each harness's names
const TOOLS = {
  claude: { read: ['Read', 'Glob', 'Grep'], write: ['Write'], edit: ['Edit'], search: ['Glob', 'Grep'], shell: ['Bash'], web: ['WebSearch', 'WebFetch'] },
  copilot: { read: ['read'], write: ['edit'], edit: ['edit'], search: ['search'], shell: ['execute'], web: ['web'] },
};
const map = (h, tools) => [...new Set(tools.flatMap(t => TOOLS[h][t] || []))];
const toolsLine = (h, a, fmt) => (a.tools ? fmt(map(h, a.tools)) : '');
const yamlStr = s => JSON.stringify(s);
const tomlStr = s => '"""\n' + s.replace(/\\/g, '\\\\').replace(/"""/g, '\\"\\"\\"') + '"""';

const agentsDir = join(root, 'agents');
for (const f of readdirSync(agentsDir).filter(f => f.endsWith('.md'))) {
  const a = parseAgent(join(agentsDir, f));
  const header = HEADER.replace('{name}', a.name);
  write(`.claude/agents/${a.name}.md`,
    `---\nname: ${a.name}\ndescription: ${yamlStr(a.description)}\n${toolsLine('claude', a, t => `tools: ${t.join(', ')}\n`)}---\n<!-- ${header} -->\n\n${a.body}`);
  write(`.codex/agents/${a.name}.toml`,
    `# ${header}\nname = ${JSON.stringify(a.name)}\ndescription = ${JSON.stringify(a.description)}\ndeveloper_instructions = ${tomlStr(a.body)}\n`);
  write(`.github/agents/${a.name}.agent.md`,
    `---\nname: ${a.name}\ndescription: ${yamlStr(a.description)}\n${toolsLine('copilot', a, t => `tools: [${t.map(x => `'${x}'`).join(', ')}]\n`)}---\n<!-- ${header} -->\n\n${a.body}`);
}

if (check) {
  if (stale.length) { console.error('✗ generated files are stale; run `node scripts/sync-agents.mjs`:\n  ' + stale.join('\n  ')); process.exit(1); }
  console.log('✓ skills and agents are in sync');
} else console.log('✓ sync complete');
